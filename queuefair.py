# Menu-driven QueueFair
import csv
customers = []
simulation_results = []
next_customer_id = 1

while True:
    print("\n====== QUEUEFAIR ======")
    print("1. Add customer")
    print("2. View customers")
    print("3. Run simulation")
    print("4. View statistics")
    print("5. Export simulation results")
    print("6. Exit")

    choice = input("Enter your choice: ")

    if choice == "1":
        while True:
            name = input("Enter customer name: ").strip()

            if name:
                break
            else:
                print("Name cannot be empty. Try again.")

        while True:
            try:
                arrival = int(input("Enter arrival time (minutes): "))

                if arrival >= 0:
                    break
                else:
                    print("Arrival time cannot be negative.")

            except ValueError:
                print("Please enter a valid whole number.")

        while True:
            try:
                service = int(input("Enter service duration (minutes): "))

                if service > 0:
                    break
                else:
                    print("Service duration must be greater than zero.")

            except ValueError:
                print("Please enter a valid whole number.")

        customer_id = f"C{next_customer_id:03d}"

        customer = {
            "id": customer_id,
            "name": name,
            "arrival": arrival,
            "service": service
        }

        customers.append(customer)
        next_customer_id += 1

        # Previous simulation results are now outdated
        simulation_results = []

        print(f"Customer {customer_id} added successfully!")

    elif choice == "2":
        if len(customers) == 0:
            print("No customers added yet.")
        else:
            print("\n========== CUSTOMER LIST ==========")
            print(
                f"{'ID':<10}"
                f"{'Name':<20}"
                f"{'Arrival Time':<20}"
                f"{'Service Time':<15}"
            )
            print("-" * 65)

            for customer in customers:
                print(
                    f"{customer['id']:<10}"
                    f"{customer['name']:<20}"
                    f"{customer['arrival']:<20}"
                    f"{customer['service']:<15}"
                )

    elif choice == "3":
        simulation_results = []

        if len(customers) == 0:
            print("No customers available. Add customers first.")

        else:
            sorted_customers = sorted(
                customers,
                key=lambda customer: customer["arrival"]
            )

            current_time = 0

            print("\n========== QUEUE SIMULATION ==========")
            print(
                f"{'ID':<10}"
                f"{'Name':<15}"
                f"{'Arrival':<12}"
                f"{'Start':<12}"
                f"{'Finish':<12}"
                f"{'Waiting':<12}"
            )
            print("-" * 73)

            for customer in sorted_customers:
                start = max(customer["arrival"], current_time)
                finish = start + customer["service"]
                waiting = start - customer["arrival"]

                simulation_results.append({
                    "id": customer["id"],
                    "name": customer["name"],
                    "arrival": customer["arrival"],
                    "service": customer["service"],
                    "start": start,
                    "finish": finish,
                    "waiting": waiting
                })

                print(
                    f"{customer['id']:<10}"
                    f"{customer['name']:<15}"
                    f"{customer['arrival']:<12}"
                    f"{start:<12}"
                    f"{finish:<12}"
                    f"{waiting:<12}"
                )

                current_time = finish
            print("\n========== SIMULATION SUMMARY ==========")
            print(f"Customers served: {len(simulation_results)}")
            print(f"Service counter available at: {current_time} minutes")

    elif choice == "4":
        if len(simulation_results) == 0:
            print("Please run the simulation first.")

        else:
            total_customers = len(simulation_results)

            total_waiting = sum(
                customer["waiting"]
                for customer in simulation_results
            )

            average_waiting = total_waiting / total_customers

            max_waiting = max(
                customer["waiting"]
                for customer in simulation_results
            )

            total_time = max(
                customer["finish"]
                for customer in simulation_results
            )

            print("\n========== QUEUE STATISTICS ==========")
            print(f"Total customers: {total_customers}")
            print(f"Average waiting time: {average_waiting:.2f} minutes")
            print(f"Maximum waiting time: {max_waiting} minutes")
            print(f"Total completion time: {total_time} minutes")

    elif choice == "5":
      if len(simulation_results) == 0:
        print("Please run the simulation first.")

      else:
        with open("queuefair_results.csv", "w", newline="") as file:
            fieldnames = [
                "id",
                "name",
                "arrival",
                "service",
                "start",
                "finish",
                "waiting"
            ]

            writer = csv.DictWriter(file, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(simulation_results)

        print("Simulation results exported to queuefair_results.csv")
    elif choice=="6":
      print("Thank you for using QueueFair!")
      break

    else:
        print("Invalid choice. Please select 1-6.")

